"""Generate area settings from config/public.json, or check committed output."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(root: Path) -> dict[str, str]:
    settings = json.loads((root / "config/public.json").read_text(encoding="utf-8"))
    origin = settings["workerOrigin"]
    match = re.fullmatch(r"https://([a-z0-9-]+(?:\.[a-z0-9-]+)+)", origin)
    if not match:
        raise ValueError("workerOrigin must be a bare HTTPS origin with a DNS hostname")
    return {
        "growth/public_config.py": (
            "# Generated by scripts/generate_public_config.py from config/public.json.\n"
            f"WORKER_URL = {json.dumps(origin)}\n"
            f"WORKER_HOST = {json.dumps(match[1])}\n"
        ),
        "extension/lib/config.js": (
            "// Public build settings. Nothing secret belongs here: the Gemini key lives only in the Worker.\n"
            "// See worker/API.md.\n"
            f"export const WORKER_URL = {json.dumps(origin)};\n"
        ),
        "worker/src/public-config.js": (
            "// Generated by scripts/generate_public_config.py from config/public.json.\n"
            f"export const WORKER_URL = {json.dumps(origin)};\n"
        ),
    }


def generate(root: Path, *, check: bool) -> list[str]:
    stale = []
    for name, content in render(root).items():
        path = root / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(name)
        if not check:
            path.write_text(content, encoding="utf-8", newline="\n")
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = generate(ROOT, check=args.check)
    if args.check and changed:
        parser.exit(1, "Stale public config: " + ", ".join(changed) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
