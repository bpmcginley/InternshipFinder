import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { AUTH, ROUTES, SPECIAL_ROUTES } from "../src/api-contract.js";

const details = new URL("../API.details.md", import.meta.url);
const output = new URL("../API.md", import.meta.url);
const cell = (text) => String(text).replaceAll("|", "\\|").replaceAll("\n", " ");

export function generateApi() {
  const rows = [...ROUTES, ...SPECIAL_ROUTES].map(
    (r) =>
      `| \`${r.method} ${r.path}\` | ${cell(r.auth)} | ${cell(r.gate)} | ${cell(r.request)} | ${cell(r.response)} |`,
  );
  const auth = Object.entries(AUTH).map(([name, description]) => `- **${name}:** ${description}`);
  return [
    "# InternScout Worker API (v1)",
    "",
    "<!-- Generated by node worker/scripts/generate-api.mjs; do not edit API.md directly. -->",
    "Route source: `src/api-contract.js`. Detailed notes: `API.details.md`.",
    "This describes checked-in code, not deployed feature configuration. Shapes are descriptive; this table does not validate requests or replace runtime authorization.",
    "",
    "## Route contract",
    "",
    "The router trims trailing slashes before exact matching. Global OPTIONS is handled first; the media prefix delegates validation and unsupported methods to social-video.js. The attached top-up recovery route returns 405 for other methods. Other unknown method/path pairs return 404. Common errors and CORS behavior remain documented below.",
    "",
    "| Method and path | Authentication | Feature gate | Request shape | Response shape |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    "### Authentication keys",
    "",
    ...auth,
    "",
    "Feature gates name the existing sync, payment or order checks; their ordering and effects remain in runtime code. Combined authentication keys require both existing checks. Request/response types such as Provider, Placement and GeminiRequest are expanded in the detailed notes and existing handler modules.",
    "",
    readFileSync(details, "utf8").replaceAll("\r\n", "\n").trimEnd(),
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== generateApi()) {
      console.error("API.md is stale; run node worker/scripts/generate-api.mjs");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(output, generateApi());
  }
}
